def create_method_model(method_name: str, **kwargs: Any) -> BaseModel:
    """Instantiates any of the study methods by its catalog key or registry alias."""
    key = method_name.lower().strip()
    if key == "sam_cbr_edgenet":
        key = "sam_cebnet"
    if key in METHOD_CATALOG:
        reg_name = METHOD_CATALOG[key]["registry_name"]
        return build_model(reg_name, **kwargs)
    return build_model(key, **kwargs)


